window.addEventListener("DOMContentLoaded", () => {
  // 1. Render lucide icons first so captured originals contain final markup
  if (window.lucide) {
    window.lucide.createIcons();
  }

  // 1.5 Terminal loader
  (function(){
    var lines = document.querySelectorAll('#terminal-content .terminal-line');
    var loader = document.getElementById('terminal-loader');
    if (!loader) return;
    document.body.style.overflow = 'hidden';
    var done = false;
    var t = 0;
    var hideLoader = function(){
      loader.classList.add('hidden');
      document.body.style.overflow = '';
    };
    lines.forEach(function(l, i){
      t += parseInt(l.getAttribute('data-delay')) || 400;
      setTimeout(function(){
        if (done) return;
        l.classList.add('visible');
        if (i === lines.length - 1) {
          setTimeout(function(){
            if (!done) { done = true; hideLoader(); }
          }, 1000);
        }
      }, t);
    });
    setTimeout(function(){
      if (!done) { done = true; hideLoader(); }
    }, t + 2200);
    window.skipTerminal = function(){
      if (done) return;
      done = true;
      lines.forEach(function(l){ l.classList.add('visible'); });
      setTimeout(hideLoader, 300);
    };
  })();

  // 2. Capture original (Chinese) content
  const originals = new Map();
  const originalsHtml = new Map();
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    originals.set(node.dataset.i18n, node.textContent);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    originalsHtml.set(node.dataset.i18nHtml, node.innerHTML);
  });

  // 3. Language toggle
  const toggle = document.querySelector("[data-lang-toggle]");
  const getStoredLanguage = () => {
    try { return localStorage.getItem("siteLanguage") || "zh"; } catch { return "zh"; }
  };
  const setStoredLanguage = (lang) => {
    try { localStorage.setItem("siteLanguage", lang); } catch { /* ignore */ }
  };

  const applyLanguage = (lang) => {
    const isEn = lang === "en";
    document.documentElement.lang = isEn ? "en" : "zh-CN";
    document.title = isEn
      ? "Zang Ke | AI Native · Data Analytics · Operations"
      : "臧珂 | AI Native · 数据分析 · 运营";

    document.querySelectorAll("[data-i18n]").forEach((node) => {
      const key = node.dataset.i18n;
      if (isEn && enTranslations[key] !== undefined) {
        node.textContent = enTranslations[key];
      } else if (!isEn && originals.has(key)) {
        node.textContent = originals.get(key);
      }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((node) => {
      const key = node.dataset.i18nHtml;
      if (isEn && enTranslationsHtml[key] !== undefined) {
        node.innerHTML = enTranslationsHtml[key];
      } else if (!isEn && originalsHtml.has(key)) {
        node.innerHTML = originalsHtml.get(key);
      }
    });

    // Re-render lucide icons injected via innerHTML
    if (window.lucide) {
      window.lucide.createIcons();
    }

    document.querySelectorAll("[data-lang-option]").forEach((node) => {
      node.classList.toggle("active", node.dataset.langOption === lang);
    });
    if (toggle) {
      toggle.setAttribute("aria-label", isEn ? "切换到中文" : "Switch to English");
    }
    setStoredLanguage(lang);
  };

  if (toggle) {
    toggle.addEventListener("click", () => {
      const current = getStoredLanguage();
      applyLanguage(current === "zh" ? "en" : "zh");
    });
  }

  applyLanguage(getStoredLanguage());

  // 4. Snapshot carousel
  document.querySelectorAll("[data-snapshot-carousel]").forEach((carousel) => {
    const cards = Array.from(carousel.querySelectorAll("[data-snapshot-card]"));
    const prev = carousel.querySelector("[data-carousel-prev]");
    const next = carousel.querySelector("[data-carousel-next]");
    const dotsWrap = carousel.querySelector("[data-carousel-dots]");
    let active = 0;

    const dots = cards.map((_, index) => {
      const dot = document.createElement("button");
      dot.type = "button";
      dot.className = "carousel-dot";
      dot.setAttribute("aria-label", `Item ${index + 1}`);
      dot.addEventListener("click", () => { active = index; render(); });
      dotsWrap.appendChild(dot);
      return dot;
    });

    const render = () => {
      cards.forEach((card, index) => {
        const offset = (index - active + cards.length) % cards.length;
        let state = "far";
        if (offset === 0) state = "active";
        if (offset === 1) state = "next";
        if (offset === cards.length - 1) state = "prev";
        card.dataset.cardState = state;
        card.setAttribute("aria-hidden", state === "far" ? "true" : "false");
      });
      dots.forEach((dot, index) => {
        dot.classList.toggle("active", index === active);
      });
    };

    prev.addEventListener("click", () => {
      active = (active - 1 + cards.length) % cards.length;
      render();
    });

    next.addEventListener("click", () => {
      active = (active + 1) % cards.length;
      render();
    });

    render();
  });

  // 5. Lightbox (with zoom + drag) — 用 width 缩放而非 transform，
  // 让 Chrome 高质量缩放算法生效，避免 GPU transform 插值导致的模糊
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightboxImg");
  const lightboxStage = document.getElementById("lightboxStage");
  const lightboxClose = lightbox.querySelector(".lightbox-close");
  const lightboxZoomIn = document.getElementById("lightboxZoomIn");
  const lightboxZoomOut = document.getElementById("lightboxZoomOut");
  const lightboxZoomReset = document.getElementById("lightboxZoomReset");

  const LB_MIN = 1;
  const LB_MAX = 4;
  const LB_STEP = 0.25;
  let lbScale = 1;
  let lbTy = 0;       // 垂直偏移（>0 向下，<0 向上）

  // 计算图片在 LB_MIN 状态下能完全显示在视口内的最大尺寸（JS 算：保证宽高都不超）
  const lbFit = () => {
    const vw = window.innerWidth * 0.92;
    const vh = window.innerHeight * 0.88 - 80; // 80px 留给工具栏
    const nw = lightboxImg.naturalWidth || lightboxImg.width || 1;
    const nh = lightboxImg.naturalHeight || lightboxImg.height || 1;
    const r = nw / nh;
    let w, h;
    if (r >= vw / vh) {
      // 宽主导：以宽为限
      w = vw;
      h = w / r;
    } else {
      // 高主导：以高为限
      h = vh;
      w = h * r;
    }
    return { w, h, r };
  };

  const lbClampTy = () => {
    if (lbScale === LB_MIN) { lbTy = 0; return; }
    const fit = lbFit();
    const imgH = fit.h * lbScale;
    const stageH = window.innerHeight * 0.88;
    const overflow = Math.max(0, (imgH - stageH) / 2);
    lbTy = Math.min(overflow, Math.max(-overflow, lbTy));
  };

  const lbApply = () => {
    if (lbScale === LB_MIN) {
      const fit = lbFit();
      lightboxImg.style.width = fit.w + "px";
      lightboxImg.style.height = fit.h + "px";
      lightboxImg.style.maxWidth = "";
      lightboxImg.style.maxHeight = "";
      lightboxImg.style.marginLeft = "0px";
      lightboxImg.style.marginTop = "0px";
      lbTy = 0;
    } else {
      // 缩放状态：按 fit 尺寸 × scale
      const fit = lbFit();
      const w = fit.w * lbScale;
      const h = fit.h * lbScale;
      lightboxImg.style.width = w + "px";
      lightboxImg.style.height = h + "px";
      lightboxImg.style.maxWidth = "none";
      lightboxImg.style.maxHeight = "none";
      lightboxImg.style.marginLeft = "0px";
      lbClampTy();
      lightboxImg.style.marginTop = lbTy + "px";
    }
    lightboxStage.classList.toggle("is-zoomed", lbScale > LB_MIN);
    lightboxZoomReset.textContent = `${Math.round(lbScale * 100)}%`;
    lightboxZoomOut.disabled = lbScale <= LB_MIN;
    lightboxZoomIn.disabled = lbScale >= LB_MAX;
  };

  const lbReset = () => {
    lbScale = 1;
    lbTy = 0;
    lbApply();
  };

  const lbZoomBy = (delta) => {
    const next = Math.min(LB_MAX, Math.max(LB_MIN, +(lbScale + delta).toFixed(2)));
    if (next === lbScale) return;
    lbScale = next;
    if (lbScale === LB_MIN) lbTy = 0;
    lbApply();
  };

  // 滚轮滑动（在缩放状态下）
  const lbScrollBy = (dy) => {
    if (lbScale <= LB_MIN) return;
    lbTy += dy;
    lbClampTy();
    lightboxImg.style.marginTop = lbTy + "px";
  };

  document.querySelectorAll("[data-lightbox]").forEach((img) => {
    img.addEventListener("click", () => {
      // 等待图片加载完成（拿到 naturalWidth/Height）再做适配
      lightboxImg.onload = () => lbReset();
      lightboxImg.src = img.src;
      lightboxImg.alt = img.alt;
      lightbox.classList.add("active");
      document.body.style.overflow = "hidden";
    });
  });

  const closeLightbox = () => {
    lightbox.classList.remove("active");
    document.body.style.overflow = "";
    // 清空 src，避免下次打开前浏览器缓存了上次图片
    lightboxImg.removeAttribute("src");
    lightboxImg.onload = null;
    lbReset();
  };

  lightboxClose.addEventListener("click", closeLightbox);
  lightbox.addEventListener("click", (e) => {
    if (e.target === lightbox || e.target === lightboxStage) closeLightbox();
  });

  lightboxZoomIn.addEventListener("click", (e) => { e.stopPropagation(); lbZoomBy(LB_STEP); });
  lightboxZoomOut.addEventListener("click", (e) => { e.stopPropagation(); lbZoomBy(-LB_STEP); });
  lightboxZoomReset.addEventListener("click", (e) => { e.stopPropagation(); lbReset(); });
  // 点击图片：100% ↔ 200% 切换（单击缩放）
  lightboxImg.addEventListener("click", (e) => {
    e.stopPropagation();
    if (lbScale === LB_MIN) lbZoomBy(1);
    else lbReset();
  });
  // 双击图片：100% ↔ 250% 切换（更激进的缩放）
  lightboxImg.addEventListener("dblclick", (e) => {
    e.stopPropagation();
    if (lbScale === LB_MIN) lbZoomBy(1.5);
    else lbReset();
  });

  // 滚轮：缩放状态 = 上下滑动；非缩放状态 = 缩放
  lightboxStage.addEventListener("wheel", (e) => {
    if (!lightbox.classList.contains("active")) return;
    e.preventDefault();
    if (lbScale > LB_MIN) {
      lbScrollBy(e.deltaY);
    } else {
      lbZoomBy(e.deltaY < 0 ? LB_STEP : -LB_STEP);
    }
  }, { passive: false });

  // 键盘
  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("active")) return;
    if (e.key === "Escape") closeLightbox();
    else if (e.key === "+" || e.key === "=") lbZoomBy(LB_STEP);
    else if (e.key === "-" || e.key === "_") lbZoomBy(-LB_STEP);
    else if (e.key === "0") lbReset();
    else if (lbScale > LB_MIN && e.key === "ArrowUp")   { e.preventDefault(); lbScrollBy(-80); }
    else if (lbScale > LB_MIN && e.key === "ArrowDown") { e.preventDefault(); lbScrollBy(80); }
    else if (lbScale > LB_MIN && e.key === "PageUp")    { e.preventDefault(); lbScrollBy(-window.innerHeight * 0.5); }
    else if (lbScale > LB_MIN && e.key === "PageDown")  { e.preventDefault(); lbScrollBy(window.innerHeight * 0.5); }
  });

  // 6. Copy to clipboard
  const toast = document.getElementById("copyToast");

  document.querySelectorAll("[data-copy]").forEach((btn) => {
    btn.addEventListener("click", async () => {
      const text = btn.dataset.copy;
      const labelZh = btn.dataset.copyLabel || "内容";
      const isEn = getStoredLanguage() === "en";
      const labelEn = labelZh === "邮箱" ? "Email" : labelZh === "电话" ? "Phone number" : "Content";
      const message = isEn ? `${labelEn} copied to clipboard` : `${labelZh}已复制到剪贴板`;
      try {
        await navigator.clipboard.writeText(text);
        showToast(message);
      } catch {
        const textarea = document.createElement("textarea");
        textarea.value = text;
        textarea.style.position = "fixed";
        textarea.style.opacity = "0";
        document.body.appendChild(textarea);
        textarea.select();
        document.execCommand("copy");
        document.body.removeChild(textarea);
        showToast(message);
      }
    });
  });

  function showToast(message) {
    if (!toast) return;
    toast.textContent = message;
    toast.classList.add("show");
    setTimeout(() => {
      toast.classList.remove("show");
    }, 2000);
  }
});
